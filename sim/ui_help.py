# Dock blocks, plus the top strip. One page each.
PAGES = ("camera", "lidar", "brain", "journal", "controls", "bar")


def page(name: str) -> tuple:
    """``(title, [(kind, text), ...])``. ``kind`` is ``h`` or ``p``."""
    title, blocks = _PAGES[name]
    return title, blocks


def wrap_text(text: str, measure, width: int) -> list:
    """Break ``text`` into lines that ``measure`` says fit in ``width``."""
    width = max(8, int(width))
    words = str(text).split()
    if not words:
        return [""]
    lines = []
    cur = ""
    for word in words:
        if measure(word) > width:
            if cur:
                lines.append(cur)
                cur = ""
            chunk = ""
            for ch in word:
                trial = chunk + ch
                if chunk and measure(trial) > width:
                    lines.append(chunk)
                    chunk = ch
                else:
                    chunk = trial
            cur = chunk
            continue
        trial = word if not cur else cur + " " + word
        if measure(trial) <= width:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


def layout_page(name: str, measure, width: int, line_h: int) -> tuple:
    """``(rows, height)``. A row is ``(y, kind, line)`` from the top of the text."""
    _title, blocks = page(name)
    rows = []
    y = 0
    step = max(1, int(line_h))
    for kind, text in blocks:
        for line in wrap_text(text, measure, width):
            rows.append((y, kind, line))
            y += step
        y += 6
    return rows, y


